const assert = require('node:assert/strict');
const {parse,summarize} = require('./parser');
const wrap = message => `[1789106823.129295][tid 12][W][restore 15] ${message}`;
assert.equal(parse(wrap('restore usb start attempt=1'),'x',1).event,'执行');
assert.equal(parse(wrap('restore usb command completed'),'x',1).event,'命令完成');
assert.equal(parse(wrap('restore usb command failed to start'),'x',1).event,'命令失败');
assert.equal(parse(wrap('restore usb pending cleared cause=test'),'x',1).event,'等待取消');
assert.equal(parse(wrap('ignore restore usb manual insert'),'x',1).event,'');
const row=parse(wrap('restore usb requested cause=hardware evidence=/dev/a missing side=left'),'x',7);
assert.deepEqual(row.fields,{cause:'hardware',evidence:'/dev/a missing',side:'left'});
assert.equal(row.line,7);assert.equal(row.level,'WARNING');assert.ok(Number.isFinite(row.time));
assert.equal(parse('[audio][INFO][2026-09-11 12:00:00] ready','x',1).level,'INFO');
assert.equal(parse('unclassified text','x',1).level,'UNKNOWN');
assert.equal(parse(wrap('message contains ERROR'),'x',1).level,'WARNING');
assert.equal(parse('[1][FATAL] failure error_code=UGR-80-03','x',1).level,'ERROR');
assert.equal(parse('\x1b[31m[ERROR] fail\x1b[0m','x',1).level,'ERROR');
const s=summarize(['restore usb start attempt=1','restore usb symlinks waiting','restore usb command completed'].map(x=>parse(wrap(x),'x',1)));
assert.equal(s.events['执行'],1);assert.equal(s.events['恢复成功'],undefined);
console.log('Parser regression checks passed');
