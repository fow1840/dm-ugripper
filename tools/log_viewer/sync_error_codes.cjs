// Development-only: refresh the offline reference from the maintained Markdown table.
const fs = require('node:fs');
const path = require('node:path');
const source = path.resolve(__dirname, '../../docs/error code/Ugripper错误码对照表.md');
const mappings = {};
for (const line of fs.readFileSync(source, 'utf8').split('\n')) {
  const cells = line.split('|').slice(1,-1).map(s=>s.trim().replace(/`/g,''));
  if (!/^UGR-\d{2}-\d{2}$/.test(cells[0] || '') || cells.length!==3) continue;
  (mappings[cells[0]] ||= []).push({type:cells[1], condition:cells[2]});
}
if (!Object.keys(mappings).length) throw new Error('No error code mappings found');
const descriptions = JSON.parse(fs.readFileSync(path.join(__dirname,'error_descriptions.json'),'utf8'));
for (const code of Object.keys(mappings)) {
  if (!descriptions[code]) throw new Error('Missing Chinese description: '+code);
}
for (const code of Object.keys(descriptions)) {
  if (!mappings[code]) throw new Error('Description has no reference mapping: '+code);
}
fs.writeFileSync(path.join(__dirname,'error_codes.js'), '// Generated by sync_error_codes.cjs from docs/error code/Ugripper错误码对照表.md\n' +
  'globalThis.ErrorCodeReference = '+JSON.stringify(descriptions,null,2)+';\n');
console.log('Updated '+Object.keys(mappings).length+' error codes');
